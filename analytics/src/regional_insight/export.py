"""Export processed marts and database seed SQL consumed by the Spring API."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def _sql_text(value: object) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def _sql_number(value: object) -> str:
    return "NULL" if pd.isna(value) else str(value)


def export_outputs(
    health: pd.DataFrame,
    housing: pd.DataFrame,
    specialties: pd.DataFrame,
    processed_dir: Path,
    migration_path: Path,
    specialty_migration_path: Path,
) -> None:
    processed_dir.mkdir(parents=True, exist_ok=True)
    migration_path.parent.mkdir(parents=True, exist_ok=True)
    health.to_csv(processed_dir / "health_access.csv", index=False, encoding="utf-8")
    housing.to_csv(processed_dir / "housing_market.csv", index=False, encoding="utf-8")
    specialties.to_csv(processed_dir / "health_specialties.csv", index=False, encoding="utf-8")

    lines = ["-- Generated by: python -m regional_insight.cli build", ""]
    for row in health.itertuples(index=False):
        lines.append(
            "INSERT INTO health_access_metric "
            "(region, population, elderly_population, active_clinics, elderly_share_pct, "
            "clinics_per_10k_elderly, priority_score, priority_band, period) VALUES "
            f"({_sql_text(row.region)}, {row.population}, {row.elderly_population}, "
            f"{row.active_clinics}, {row.elderly_share_pct}, {row.clinics_per_10k_elderly}, "
            f"{row.priority_score}, {_sql_text(row.priority_band)}, {_sql_text(row.period)});"
        )
    lines.append("")
    for row in housing.itertuples(index=False):
        lines.append(
            "INSERT INTO housing_market_metric "
            "(region, transaction_count, median_trade_price_krw, median_price_per_sqm_krw, "
            "median_area_sqm, price_cagr_pct, market_heat_score, market_band, period) VALUES "
            f"({_sql_text(row.region)}, {row.transaction_count}, {row.median_trade_price_krw}, "
            f"{row.median_price_per_sqm_krw}, {row.median_area_sqm}, {row.price_cagr_pct}, "
            f"{row.market_heat_score}, {_sql_text(row.market_band)}, {_sql_text(row.period)});"
        )
    migration_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    specialty_lines = [
        "-- Generated by: python -m regional_insight.cli build",
        "",
        "ALTER TABLE health_access_metric ADD COLUMN latitude NUMERIC(9, 6);",
        "ALTER TABLE health_access_metric ADD COLUMN longitude NUMERIC(9, 6);",
        "",
    ]
    for row in health.itertuples(index=False):
        specialty_lines.append(
            "UPDATE health_access_metric SET "
            f"latitude = {_sql_number(row.latitude)}, longitude = {_sql_number(row.longitude)} "
            f"WHERE region = {_sql_text(row.region)};"
        )
    specialty_lines.extend(
        [
            "",
            "CREATE TABLE health_specialty_metric (",
            "    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,",
            "    region VARCHAR(40) NOT NULL,",
            "    specialty VARCHAR(80) NOT NULL,",
            "    disease_rank INTEGER NOT NULL,",
            "    disease_patient_count BIGINT NOT NULL,",
            "    disease_share_pct NUMERIC(10, 6) NOT NULL,",
            "    active_clinics BIGINT NOT NULL,",
            "    clinics_per_10k_elderly NUMERIC(8, 2) NOT NULL,",
            "    source_scope VARCHAR(120) NOT NULL,",
            "    source_period VARCHAR(40) NOT NULL,",
            "    CONSTRAINT uq_health_specialty UNIQUE (region, specialty),",
            (
                "    CONSTRAINT fk_health_specialty_region FOREIGN KEY (region) "
                "REFERENCES health_access_metric (region)"
            ),
            ");",
            "",
            "CREATE INDEX idx_health_specialty_region_rank ON health_specialty_metric (region, disease_rank);",
            "",
        ]
    )
    for row in specialties.itertuples(index=False):
        specialty_lines.append(
            "INSERT INTO health_specialty_metric "
            "(region, specialty, disease_rank, disease_patient_count, disease_share_pct, "
            "active_clinics, clinics_per_10k_elderly, source_scope, source_period) VALUES "
            f"({_sql_text(row.region)}, {_sql_text(row.specialty)}, {row.disease_rank}, "
            f"{row.patient_count}, {row.share_pct}, {row.active_clinics}, "
            f"{row.clinics_per_10k_elderly}, {_sql_text(row.source_scope)}, "
            f"{_sql_text(row.source_period)});"
        )
    specialty_migration_path.write_text(
        "\n".join(specialty_lines) + "\n", encoding="utf-8"
    )
